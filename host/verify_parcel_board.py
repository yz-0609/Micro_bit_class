"""Destructive-to-RAM commissioning test; run only before any real trip.

Synthetic events are explicitly marked as test data. No input pin is driven.
The test finishes by resetting the board to a clean idle session.
"""
import argparse
import json
import sys
import time
from datetime import datetime

from board_link import BoardLink, ROOT
from parcel_protocol import parse, Snapshot, export_snapshot


def main():
    sys.stdout.reconfigure(encoding='utf-8', line_buffering=True)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--port', default='COM42')
    args = parser.parse_args()
    folder = ROOT / 'verification' / 'parcel_basic_verification'
    folder.mkdir(parents=True, exist_ok=True)
    report = {'test_data_only': True, 'time': datetime.now().isoformat(), 'checks': []}
    link = BoardLink(args.port)
    link.enter()
    try:
        cases = [
            ('start', "r.step(0,(0,0,-1000),1)\nr.step(100,(0,0,-1000),1)\nprint(r.cmd('START',200,512))", 'STARTED'),
            ('shock', "r.step(220,(0,0,-1800),1)\nr.step(240,(0,0,-1000),1)\nprint(r.counts)", '[1, 0, 0]'),
            ('tilt', "for t in range(400,2800,20):\n r.step(t,(1000,0,0),1)\nprint(r.counts)", '[1, 1, 0]'),
            ('opening', "r.step(2800,(1000,0,0),0)\nr.step(2880,(1000,0,0),0)\nprint(r.counts)", '[1, 1, 1]'),
            ('capacity', "for i in range(40):\n r.event('O',3000+i,0)\nprint(r.n,len(r.events),r.record(0)[0])", '43 16 28'),
            ('stop', "print(r.cmd('STOP',4000))", 'STOPPED'),
        ]
        for name, source, expected in cases:
            # opt_level(3) strips board-side asserts, including their side effects.
            # Execute actions unconditionally; verify their outputs on the host.
            output = link.execute(source).strip()
            assert output == expected, (name, output, expected)
            report['checks'].append(name)
            print('PASS', name)
        assembler = Snapshot()
        output = link.execute("from parcel_actions import command\ncommand(r,[True],'DUMP',4000,0)")
        snapshot = None
        for line in output.splitlines():
            message = parse(line)
            if message:
                snapshot = assembler.feed(message) or snapshot
        assert snapshot and snapshot['summary']['total'] == 43
        export_snapshot(snapshot, folder / 'SIMULATED_TEST_ONLY.csv')
        report['checks'].append('board_dump_and_csv_json_export')
        report['heap_full'] = int(link.execute('import gc\ngc.collect()\nprint(gc.mem_free())').strip())
        # Use the real sensors for the soak test, retaining the full synthetic buffer.
        # Match the current static switch level in RAM without writing/driving P1.
        link.execute('import microbit as m\nr.closed=r.pin=m.pin1.read_digital()\nr.base=m.accelerometer.get_values()\nr.g0=max(1,int(sum(v*v for v in r.base)**0.5))\nr.start=m.running_time()\nr.state="R"\nr.tilt=False\nr.tilt_at=-1\nr.high=False')
        link.port.write(b'parcel_hardware.run(r)\x04')
        link.until(b'OK')
        captured = bytearray(link.buffer)
        link.buffer.clear()
        end = time.monotonic() + 120
        while time.monotonic() < end:
            captured.extend(link.port.read(link.port.in_waiting or 1))
        link.port.write(b'\x03')
        time.sleep(0.5)
        captured.extend(link.port.read(link.port.in_waiting))
        (folder / 'full_buffer_real_sensor_soak.txt').write_bytes(captured)
        text = captured.decode('utf-8', 'replace')
        assert 'MemoryError' not in text
        frames = [parse(line) for line in text.splitlines()]
        frames = [frame for frame in frames if frame and frame['type'] == 'S']
        assert len(frames) >= 350, len(frames)
        assert all(frame['state'] == 'R' for frame in frames)
        report['soak_seconds'] = 120
        report['status_frames'] = len(frames)
        report['first_status'], report['last_status'] = frames[0], frames[-1]
        link.enter()
        report['heap_after_soak'] = int(link.execute('gc.collect()\nprint(gc.mem_free())').strip())
        report['checks'].append('full_buffer_120s_real_sensor_soak')
        print('PASS soak', len(frames), 'frames; heap', report['heap_after_soak'])
    finally:
        # A clean reset also discards every synthetic event generated by this test.
        link.port.write(b'\x02')
        link.port.flush()
        time.sleep(0.2)
        link.port.write(b'\x04')
        link.port.flush()
        time.sleep(2)
        link.port.close()
    report['synthetic_events_cleared_by_reset'] = True
    (folder / 'results.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print('RESULTS', folder / 'results.json')


if __name__ == '__main__':
    main()
